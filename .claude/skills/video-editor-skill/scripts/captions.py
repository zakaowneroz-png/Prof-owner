#!/usr/bin/env python3
"""Group word timings into two-line captions for the HyperFrames starter (assets/starter/assets/captions.js).

Usage: python3 captions.py words.json > captions.js
       [--max-line 4] [--max-gap 0.45] [--strong word1,word2] [--offset 0.0] [--json]

Rules (general, tune per guideline):
  * a caption is 1–2 lines, each line ≤ --max-line words; a pause > --max-gap or sentence punctuation ends it
  * words in --strong (or ending a sentence with emphasis you mark later) get a leading '*' = accent/big word
  * `out` = when the caption should leave (last word end + 0.25 s, never past the next caption's start)
Proofread the words first: captions must never show a misheard word.
"""
import json, sys, argparse

ap = argparse.ArgumentParser()
ap.add_argument("words")
ap.add_argument("--max-line", type=int, default=4)
ap.add_argument("--max-gap", type=float, default=0.45)
ap.add_argument("--strong", default="", help="comma-separated words to mark as accent words")
ap.add_argument("--offset", type=float, default=0.0, help="shift all times (e.g. when the edit trims the start)")
ap.add_argument("--json", action="store_true", help="print plain JSON instead of a JS file")
a = ap.parse_args()

words = json.load(open(a.words, encoding="utf-8"))
strong = {s.strip() for s in a.strong.split(",") if s.strip()}
END = tuple(".!?…؟،,;:")
caps, cur = [], []

def flush():
    if not cur: return
    cut = (len(cur) + 1) // 2                           # two balanced lines (one line for a single word)
    caps.append({"l1": cur[:cut], "l2": cur[cut:]})
    cur.clear()

for i, w in enumerate(words):
    cur.append(w)
    nxt = words[i + 1] if i + 1 < len(words) else None
    gap = (nxt["start"] - w["end"]) if nxt else 99
    if gap > a.max_gap or w["w"].endswith(END) or len(cur) >= 2 * a.max_line: flush()
flush()

def fmt(ws):
    return [("*" if w["w"].strip(".,!?،؟") in strong else "") + w["w"] for w in ws]

out = []
for i, c in enumerate(caps):
    allw = c["l1"] + c["l2"]
    nxt_start = (caps[i + 1]["l1"] or caps[i + 1]["l2"])[0]["start"] if i + 1 < len(caps) else 1e9
    o = min(allw[-1]["end"] + 0.25, nxt_start - 0.05)
    out.append({
        "l1": fmt(c["l1"]), "t1": [round(w["start"] + a.offset, 2) for w in c["l1"]],
        "l2": fmt(c["l2"]), "t2": [round(w["start"] + a.offset, 2) for w in c["l2"]],
        "out": round(o + a.offset, 2),
    })

if a.json:
    print("[\n " + ",\n ".join(json.dumps(c, ensure_ascii=False) for c in out) + "\n]")
else:
    print("// generated by captions.py: edit freely (prefix a word with * to make it an accent word)")
    print("window.CAPTIONS = [\n " + ",\n ".join(json.dumps(c, ensure_ascii=False) for c in out) + "\n];")
